const EMPTY = { speakers: [], topics: [], insights: [], decisions: [], actions: [], reply: "" };

/** Picks the canned answer(s) matching how much of the script has been heard so far. */
export function demoLive(m, question) {
  const heard = m.segments.length;
  const stage = heard >= DEMO_SCRIPT.length ? 3 : heard >= 9 ? 2 : heard >= 3 ? 1 : 0;
  const d = structuredClone(EMPTY);
  for (let i = m.demoStage || 0; i < stage; i++) {
    for (const k of ["speakers", "topics", "insights", "decisions", "actions"]) d[k].push(...structuredClone(DELTAS[i][k]));
  }
  m.demoStage = Math.max(stage, m.demoStage || 0);
  if (question) d.reply = "(وضع تجريبي) لما تضيف مفتاح Claude هجاوبك هنا من سياق الاجتماع لحظيًا.";
  return d;
}

